-- Минимальная Moodle-подобная схема банка вопросов.
-- Она не заменяет полную схему Moodle, а сохраняет названия и смысл основных сущностей.

CREATE TABLE IF NOT EXISTS mdl_question_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idnumber VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    contextid BIGINT,
    info TEXT,
    sortorder INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS mdl_question (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category BIGINT NOT NULL,
    idnumber VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    questiontext TEXT NOT NULL,
    questiontextformat SMALLINT NOT NULL DEFAULT 1,
    qtype VARCHAR(20) NOT NULL DEFAULT 'multichoice',
    single_answer BOOLEAN NOT NULL DEFAULT TRUE,
    difficulty VARCHAR(16) NOT NULL DEFAULT 'MEDIUM',
    defaultmark NUMERIC(12, 7) NOT NULL DEFAULT 1,
    status VARCHAR(20) NOT NULL DEFAULT 'ready',
    version INTEGER NOT NULL DEFAULT 1,
    source_question_id BIGINT,
    timecreated BIGINT NOT NULL DEFAULT 0,
    timemodified BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT mdl_question_category_fk FOREIGN KEY (category) REFERENCES mdl_question_categories(id),
    CONSTRAINT mdl_question_difficulty_ck CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD'))
);

CREATE TABLE IF NOT EXISTS mdl_question_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question BIGINT NOT NULL,
    answer TEXT NOT NULL,
    answerformat SMALLINT NOT NULL DEFAULT 1,
    fraction NUMERIC(12, 7) NOT NULL DEFAULT 0,
    feedback TEXT,
    answer_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT mdl_question_answer_fk FOREIGN KEY (question) REFERENCES mdl_question(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS mdl_quiz (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course BIGINT NOT NULL DEFAULT 1,
    idnumber VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    intro TEXT,
    created_by BIGINT,
    timelimit BIGINT NOT NULL DEFAULT 600,
    grade NUMERIC(10, 5) NOT NULL DEFAULT 100,
    visible BOOLEAN NOT NULL DEFAULT TRUE,
    source_quiz_id BIGINT,
    timecreated BIGINT NOT NULL DEFAULT 0,
    timemodified BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT mdl_quiz_author_fk FOREIGN KEY (created_by) REFERENCES mdl_user(id)
);

CREATE TABLE IF NOT EXISTS mdl_quiz_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quizid BIGINT NOT NULL,
    slot INTEGER NOT NULL,
    page INTEGER NOT NULL DEFAULT 1,
    questionid BIGINT NOT NULL,
    maxmark NUMERIC(12, 7) NOT NULL DEFAULT 1,
    CONSTRAINT mdl_quiz_slot_quiz_fk FOREIGN KEY (quizid) REFERENCES mdl_quiz(id) ON DELETE CASCADE,
    CONSTRAINT mdl_quiz_slot_question_fk FOREIGN KEY (questionid) REFERENCES mdl_question(id),
    CONSTRAINT mdl_quiz_slot_uk UNIQUE (quizid, slot)
);

CREATE INDEX IF NOT EXISTS mdl_question_category_ix ON mdl_question(category);
CREATE INDEX IF NOT EXISTS mdl_question_answers_question_ix ON mdl_question_answers(question);
CREATE INDEX IF NOT EXISTS mdl_quiz_slots_question_ix ON mdl_quiz_slots(questionid);
